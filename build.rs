//! Packs the 4x4 leaf sheets in `Assets/` into one texture atlas at build time.
//!
//! Every sheet is sliced into single leaves, the background speckles are stripped (only the
//! largest connected blob of solid pixels survives), each leaf is shrunk to fit a 120 px cell
//! and packed into a 16-column atlas. The atlas is written to `OUT_DIR` as a premultiplied
//! RGBA PNG plus a Rust source file with the cell rectangles, and both are embedded into the
//! binary so it stays self-contained.
use image::{RgbaImage, imageops::FilterType};
use std::{env, fs, path::PathBuf};

const CELL: u32 = 128; // atlas cell size in px
const INNER: u32 = 120; // max leaf extent inside a cell
const COLUMNS: u32 = 16;
const ALPHA_CUT: u8 = 80;
const GRID: u32 = 4; // each sheet is GRID x GRID leaves

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let assets = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("Assets");
    println!("cargo:rerun-if-changed={}", assets.display());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());

    let mut sheets: Vec<PathBuf> = fs::read_dir(&assets)
        .expect("Assets/ directory")
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|p| p.extension().map(|e| e.eq_ignore_ascii_case("png")).unwrap_or(false))
        .collect();
    sheets.sort();

    let mut leaves: Vec<RgbaImage> = Vec::new();
    for path in &sheets {
        println!("cargo:rerun-if-changed={}", path.display());
        let sheet = match image::open(path) {
            Ok(img) => img.to_rgba8(),
            Err(err) => {
                println!("cargo:warning=skipping unreadable {}: {err}", path.display());
                continue;
            }
        };
        let size = sheet.width().min(sheet.height()) / GRID;
        for row in 0..GRID {
            for col in 0..GRID {
                if let Some(leaf) = extract_leaf(&sheet, col * size, row * size, size) {
                    leaves.push(leaf);
                }
            }
        }
    }
    assert!(!leaves.is_empty(), "no leaves found in {}", assets.display());

    let rows = (leaves.len() as u32).div_ceil(COLUMNS);
    let (atlas_w, atlas_h) = (COLUMNS * CELL, rows * CELL);
    let mut atlas = RgbaImage::new(atlas_w, atlas_h);
    let mut rects: Vec<[u32; 4]> = Vec::with_capacity(leaves.len());
    for (i, leaf) in leaves.iter().enumerate() {
        let scale = (INNER as f32 / leaf.width() as f32)
            .min(INNER as f32 / leaf.height() as f32)
            .min(1.0);
        let w = (leaf.width() as f32 * scale).round().max(1.0) as u32;
        let h = (leaf.height() as f32 * scale).round().max(1.0) as u32;
        let premultiplied = premultiply(leaf);
        let resized = if scale < 1.0 {
            clamp_premultiplied(image::imageops::resize(&premultiplied, w, h, FilterType::Triangle))
        } else {
            premultiplied
        };
        let x = (i as u32 % COLUMNS) * CELL + (CELL - w) / 2;
        let y = (i as u32 / COLUMNS) * CELL + (CELL - h) / 2;
        image::imageops::replace(&mut atlas, &resized, x as i64, y as i64);
        rects.push([x, y, w, h]);
    }

    atlas.save(out.join("leaf_atlas.png")).expect("write atlas png");

    let mut source = String::new();
    source.push_str("// Generated by build.rs from the sheets in Assets/. Do not edit by hand.\n");
    source.push_str(&format!("pub const ATLAS_WIDTH: u32 = {atlas_w};\n"));
    source.push_str(&format!("pub const ATLAS_HEIGHT: u32 = {atlas_h};\n"));
    source.push_str("/// [x, y, w, h] cells in atlas pixels, origin top-left.\n");
    source.push_str("pub const RECTS: &[[u16; 4]] = &[\n");
    for r in &rects {
        source.push_str(&format!("    [{}, {}, {}, {}],\n", r[0], r[1], r[2], r[3]));
    }
    source.push_str("];\n");
    fs::write(out.join("leaf_atlas_rects.rs"), source).expect("write atlas rects");
    println!(
        "cargo:warning=leaf atlas {atlas_w}x{atlas_h}, {} leaves from {} sheets",
        leaves.len(),
        sheets.len()
    );
}

fn premultiply(img: &RgbaImage) -> RgbaImage {
    let mut out = img.clone();
    for p in out.pixels_mut() {
        let a = p[3] as u32;
        for c in 0..3 {
            p[c] = ((p[c] as u32 * a + 127) / 255) as u8;
        }
    }
    out
}

/// Resampling can leave a colour channel a hair above alpha; clamp so the atlas stays valid
/// premultiplied data.
fn clamp_premultiplied(mut img: RgbaImage) -> RgbaImage {
    for p in img.pixels_mut() {
        for c in 0..3 {
            p[c] = p[c].min(p[3]);
        }
    }
    img
}

/// Returns the leaf in the given region of the sheet as a tightly cropped bitmap, keeping only
/// the largest connected blob of solid pixels (the speckles around the leaves are dropped).
fn extract_leaf(sheet: &RgbaImage, x0: u32, y0: u32, size: u32) -> Option<RgbaImage> {
    let n = (size * size) as usize;
    let s = size as usize;
    let alpha = |sx: usize, sy: usize| sheet.get_pixel(x0 + sx as u32, y0 + sy as u32)[3];

    let mut label = vec![0i32; n];
    let mut best = (0i32, 0usize);
    let mut next = 1i32;
    let mut stack: Vec<usize> = Vec::new();
    for sy in 0..s {
        for sx in 0..s {
            if label[sy * s + sx] != 0 || alpha(sx, sy) < ALPHA_CUT {
                continue;
            }
            let id = next;
            next += 1;
            let mut count = 0;
            label[sy * s + sx] = id;
            stack.push(sy * s + sx);
            while let Some(idx) = stack.pop() {
                count += 1;
                let (cx, cy) = (idx % s, idx / s);
                let neighbours = [
                    (cx.wrapping_sub(1), cy),
                    (cx + 1, cy),
                    (cx, cy.wrapping_sub(1)),
                    (cx, cy + 1),
                ];
                for (nx, ny) in neighbours {
                    if nx >= s || ny >= s {
                        continue;
                    }
                    let ni = ny * s + nx;
                    if label[ni] == 0 && alpha(nx, ny) >= ALPHA_CUT {
                        label[ni] = id;
                        stack.push(ni);
                    }
                }
            }
            if count > best.1 {
                best = (id, count);
            }
        }
    }
    if best.1 <= 400 {
        return None;
    }

    // Keep the blob plus a one-pixel soft rim so anti-aliased edges survive.
    let mut keep = vec![false; n];
    let (mut min_x, mut min_y, mut max_x, mut max_y) = (s, s, 0usize, 0usize);
    let mut any = false;
    for sy in 0..s {
        for sx in 0..s {
            let is = |x: usize, y: usize| x < s && y < s && label[y * s + x] == best.0;
            let near = is(sx, sy)
                || is(sx.wrapping_sub(1), sy)
                || is(sx + 1, sy)
                || is(sx, sy.wrapping_sub(1))
                || is(sx, sy + 1);
            if near && alpha(sx, sy) > 0 {
                keep[sy * s + sx] = true;
                min_x = min_x.min(sx);
                max_x = max_x.max(sx);
                min_y = min_y.min(sy);
                max_y = max_y.max(sy);
                any = true;
            }
        }
    }
    if !any {
        return None;
    }
    let mut leaf = RgbaImage::new((max_x - min_x + 1) as u32, (max_y - min_y + 1) as u32);
    for sy in min_y..=max_y {
        for sx in min_x..=max_x {
            if keep[sy * s + sx] {
                let px = *sheet.get_pixel(x0 + sx as u32, y0 + sy as u32);
                leaf.put_pixel((sx - min_x) as u32, (sy - min_y) as u32, px);
            }
        }
    }
    Some(leaf)
}
